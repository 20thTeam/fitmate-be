package com.team20.fitmate.realtime.message;

/**
 * 프론트(클라이언트)가 실시간 서버로 보내는 메시지 종류.
 * <p>
 * 형식과 예시는 {@code docs/실시간_메시지_형식.md}에 있다. 종류를 추가하면 문서도 함께 고친다.
 */
public enum ClientMessageType {

    /** 운동방 입장. 연결 후 가장 먼저 보내야 한다. 재방문 토큰과 운동방 식별값을 담는다 */
    JOIN,

    /** 내 현재 운동·진행 상태 변경. 서버는 해석하지 않고 같은 방에 전달만 한다 */
    STATUS,

    /** 내 동작 정보(관절 위치). 서버는 해석·저장하지 않고 같은 방의 다른 참가자에게 전달만 한다 */
    POSE,

    /** 같은 방 친구 한 명에게 보내는 응원. 대상에게만 전달한다 */
    CHEER,

    /** 연결 유지 확인. 일정 시간 아무 메시지가 없으면 연결 불안정으로 본다 */
    PING,

    /** 운동방 퇴장. 보내면 바로 방에서 빠지고 연결이 닫힌다 */
    LEAVE
}
